using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Apogee.Reflection;

namespace Apogee.Scripting;

/// <summary>A global that the host sets in its VMs (<see cref="LuauVm.SetGlobal"/>), which the definitions declare for the scripts that run there.</summary>
/// <param name="Name">The global's name.</param>
/// <param name="Type">Its type in Luau, such as <c>World</c>.</param>
/// <param name="Doc">One line for hover, or null.</param>
public sealed record HostGlobal(string Name, string Type, string? Doc = null);

/// <summary>What a host adds to or takes out of the definitions.</summary>
public sealed class DefinitionOptions
{
    /// <summary>The globals the host sets, such as <c>world</c>.</summary>
    public IReadOnlyList<HostGlobal> Globals { get; init; } = [];

    /// <summary>Classes that are registered for scripts but kept out of the definitions (the runtime's smoke test class). Others see them as <c>EngineObject</c>.</summary>
    public IReadOnlyCollection<string> HiddenClasses { get; init; } = [];
}

/// <summary>
/// Writes the engine's API as Luau type definitions (<c>apogee.d.luau</c>) for luau-lsp, from the registry: the classes, enums and script
/// libraries the generator described, and the hand-written natives with the declarations they were registered with. The output depends only on
/// the registry, in a fixed order.
/// </summary>
public static class DefinitionWriter
{
    private static readonly HashSet<string> s_keywords = new(StringComparer.Ordinal)
    {
        "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil", "not", "or", "repeat",
        "return", "then", "true", "until", "while", "continue", "export", "type", "typeof",
    };

    /// <summary>The definitions of everything registered now.</summary>
    public static string Write(DefinitionOptions? options = null)
    {
        LuauVm.EnsureEngineClasses();
        LuauVm.RegisterEcsNatives();
        LuauVm.RegisterContentNatives();
        return Write(TypeRegistry.Classes, TypeRegistry.Enums, TypeRegistry.Libraries, options);
    }

    public static string Write(IReadOnlyList<ClassInfo> classes, IReadOnlyList<EnumInfo> enums, IReadOnlyList<LibraryInfo> libraries, DefinitionOptions? options = null)
    {
        options ??= new DefinitionOptions();
        var enumsByName = enums.ToDictionary(e => e.Name, StringComparer.Ordinal);
        var scriptable = classes.Where(c => c.Scriptable && !options.HiddenClasses.Contains(c.Name)).ToList();
        var classNames = new HashSet<string>(scriptable.Select(c => c.Name), StringComparer.Ordinal);

        var text = new StringBuilder();
        Line(text, "-- Luau type definitions of the engine API, for luau-lsp (\"luau-lsp.types.definitionFiles\").");
        Line(text, "-- Generated by the engine with --luau-defs; do not edit.");
        text.Append('\n');
        Line(text, "type Vector3 = vector");
        Line(text, "type Entity = number");
        Line(text, "type FieldType = \"bool\" | \"i8\" | \"u8\" | \"i16\" | \"u16\" | \"i32\" | \"u32\" | \"i64\" | \"u64\" | \"f32\" | \"f64\" | \"vec3\" | \"dvec3\" | \"quat\" | \"entity\"");
        Line(text, "type Phase = \"on_load\" | \"post_load\" | \"pre_update\" | \"on_update\" | \"on_validate\" | \"post_update\" | \"pre_store\" | \"on_store\"");
        Line(text, "type Term = number | { any }");
        Line(text, "type ComponentView = { [string]: any }");
        Line(text, "type XmlElement = { name: string, attrs: { [string]: string }, order: { string }, children: { XmlElement }, text: string, line: number }");
        Line(text, "type PackageInfo = { id: string, name: string, version: string, author: string, description: string, kind: string, loads: boolean, reason: string?, ran: boolean, error: string? }");
        Line(text, "type DefSource = { package: string, path: string, line: number, role: string }");
        Line(text, "type DefProblem = { severity: string, path: string, file: string?, line: number, message: string }");
        text.Append('\n');
        Line(text, "declare extern type Connection with");
        Line(text, "    connected: boolean");
        Line(text, "    function disconnect(self): ()");
        Line(text, "end");
        text.Append('\n');
        Line(text, "type Signal<T...> = { connect: (self: Signal<T...>, handler: (T...) -> ()) -> Connection }");

        foreach (EnumInfo info in enums.OrderBy(e => e.Name, StringComparer.Ordinal))
        {
            text.Append('\n');
            AppendDoc(text, info.Doc, "");
            Line(text, $"type {info.Name} = {(info.Members.Count == 0 ? "string" : string.Join(" | ", info.Members.Select(m => $"\"{m.Name}\"")))}");
        }

        text.Append('\n');
        Line(text, "declare extern type EngineObject with");
        Line(text, "end");

        var context = new Context(enumsByName, classNames);
        foreach (ClassInfo info in OrderedByInheritance(scriptable).Where(c => c.Name != "EngineObject"))
        {
            text.Append('\n');
            AppendClass(text, info, context);
        }

        foreach (ClassInfo info in scriptable.Where(c => c.Name != "EngineObject").OrderBy(c => c.Name, StringComparer.Ordinal))
        {
            List<string> members = [];
            if (info.Creatable)
            {
                members.Add($"new: () -> {info.Name}");
            }

            members.AddRange(info.Methods.Where(m => m.IsStatic && IsIdentifier(m.ScriptName)).Select(m => $"{m.ScriptName}: {FunctionType(m, context)}"));
            if (members.Count > 0)
            {
                text.Append('\n');
                Line(text, $"declare {info.Name}: {{ {string.Join(", ", members)} }}");
            }
        }

        foreach (LibraryInfo library in libraries.OrderBy(l => l.Name, StringComparer.Ordinal))
        {
            text.Append('\n');
            AppendDoc(text, library.Doc, "");
            Line(text, $"declare {library.Name}: {{");
            foreach (MethodDef method in library.Methods.Where(m => IsIdentifier(m.ScriptName)))
            {
                AppendDoc(text, method.Doc, "    ");
                Line(text, $"    {method.ScriptName}: {FunctionType(method, context)},");
            }

            Line(text, "}");
        }

        foreach ((string name, IReadOnlyList<ScriptNatives.NativeFunction> functions) in ScriptNatives.Libraries())
        {
            text.Append('\n');
            Line(text, $"declare {name}: {{");
            foreach (ScriptNatives.NativeFunction function in functions)
            {
                AppendDoc(text, function.Doc, "    ");
                Line(text, $"    {function.Name}: {function.Type},");
            }

            Line(text, "}");
        }

        foreach (HostGlobal global in options.Globals)
        {
            text.Append('\n');
            AppendDoc(text, global.Doc, "");
            Line(text, $"declare {global.Name}: {global.Type}");
        }

        text.Append('\n');
        Line(text, "declare function Vector3(x: number?, y: number?, z: number?): vector");
        text.Append('\n');
        Line(text, "-- A rotation. a * b applies b first, then a; q * vector rotates the vector. Euler angles are radians as (pitch about x, yaw about y, roll about z).");
        Line(text, "declare extern type Quat with");
        Line(text, "    x: number");
        Line(text, "    y: number");
        Line(text, "    z: number");
        Line(text, "    w: number");
        Line(text, "    function inverse(self): Quat");
        Line(text, "    function normalized(self): Quat");
        Line(text, "    function slerp(self, other: Quat, t: number): Quat");
        Line(text, "    function dot(self, other: Quat): number");
        Line(text, "    function toEuler(self): vector");
        Line(text, "    __mul: ((Quat, Quat) -> Quat) & ((Quat, vector) -> vector)");
        Line(text, "end");
        text.Append('\n');
        Line(text, "declare Quat: {");
        Line(text, "    identity: Quat,");
        Line(text, "    new: (x: number, y: number, z: number, w: number) -> Quat,");
        Line(text, "    axisAngle: (axis: vector, radians: number) -> Quat,");
        Line(text, "    euler: (angles: vector) -> Quat,");
        Line(text, "    lookAt: (forward: vector, up: vector?) -> Quat,");
        Line(text, "}");
        text.Append('\n');
        Line(text, "declare function warn(...: any): ()");
        return text.ToString();
    }

    /// <summary>Always <c>\n</c>: the file is the same on every platform.</summary>
    private static void Line(StringBuilder text, string line) => text.Append(line).Append('\n');

    internal sealed record Context(Dictionary<string, EnumInfo> Enums, HashSet<string> Classes);

    private static void AppendClass(StringBuilder text, ClassInfo info, Context context)
    {
        AppendDoc(text, info.Doc, "");
        string parent = info.BaseName is { } name && context.Classes.Contains(name) ? name : "EngineObject";
        Line(text, $"declare extern type {info.Name} extends {parent} with");

        foreach (PropertyDef property in info.Properties.Where(p => IsIdentifier(p.ScriptName)))
        {
            AppendDoc(text, WithRange(property.Doc, property.Meta), "    ");
            Line(text, $"    {property.ScriptName}: {TypeName(property.Type, context)}");
        }

        foreach (SignalDef signal in info.Signals.Where(s => IsIdentifier(s.ScriptName)))
        {
            AppendDoc(text, signal.Doc, "    ");
            Line(text, $"    {signal.ScriptName}: Signal<{(signal.Parameters.Length == 0 ? "()" : string.Join(", ", signal.Parameters.Select(p => TypeName(p.Type, context))))}>");
        }

        foreach (MethodDef method in info.Methods.Where(m => !m.IsStatic && IsIdentifier(m.ScriptName)))
        {
            AppendDoc(text, method.Doc, "    ");
            Line(text, $"    function {method.ScriptName}(self{string.Concat(method.Parameters.Select(p => ", " + ParameterText(p, context)))}): {ResultText(method, context)}");
        }

        foreach (ScriptNatives.NativeMethod native in ScriptNatives.Of(info.Name))
        {
            Line(text, $"    {native.Declaration}");
        }

        Line(text, "end");
    }

    private static IEnumerable<ClassInfo> OrderedByInheritance(List<ClassInfo> classes)
    {
        int Depth(ClassInfo info)
        {
            int depth = 0;
            for (ClassInfo? current = info.Base; current is not null; current = current.Base)
            {
                depth++;
            }

            return depth;
        }

        return classes.OrderBy(Depth).ThenBy(c => c.Name, StringComparer.Ordinal);
    }

    internal static string ParameterText(ParameterDef parameter, Context context)
    {
        string type = TypeName(parameter.Type, context);
        if (parameter.Optional && !type.EndsWith('?') && type != "any")
        {
            type = Optional(type, context);
        }

        return $"{ParameterName(parameter.Name)}: {type}";
    }

    private static string ParameterName(string name) => s_keywords.Contains(name) ? name + "_" : name;

    internal static string ResultText(MethodDef method, Context context) => method.Results.Length switch
    {
        0 => "()",
        1 => TypeName(method.Results[0], context),
        _ => "(" + string.Join(", ", method.Results.Select(r => TypeName(r, context))) + ")",
    };

    internal static string FunctionType(MethodDef method, Context context) =>
        $"({string.Join(", ", method.Parameters.Select(p => ParameterText(p, context)))}) -> {ResultText(method, context)}";

    internal static string TypeName(TypeRef type, Context context)
    {
        string name = type.Kind switch
        {
            ValueKind.Nil => "any",
            ValueKind.Bool => "boolean",
            ValueKind.Int or ValueKind.Float => "number",
            ValueKind.String => "string",
            ValueKind.Vector3 => "Vector3",
            ValueKind.Quaternion => "Quat",
            ValueKind.Entity => "Entity",
            ValueKind.Enum => context.Enums.TryGetValue(type.Name!, out EnumInfo? info) && info.IsFlags ? $"{{ {type.Name} }}" : type.Name!,
            ValueKind.Object => context.Classes.Contains(type.Name!) ? type.Name! : "EngineObject",
            ValueKind.Function => "(...any) -> ...any",
            ValueKind.Table => "{ [any]: any }",
            _ => $"{{ {TypeName(type.Element ?? TypeRef.Any, context)} }}",
        };

        return type.Nullable && type.Kind != ValueKind.Nil ? Optional(name, context) : name;
    }

    /// <summary>
    /// <paramref name="type"/> or nil. A function type needs parentheses before <c>?</c>. A list of flags is <c>({ Flags } | {})?</c>: luau-lsp's default type solver
    /// rejects a table literal such as <c>{ "no_move" }</c> against <c>{ Flags }?</c> (it infers <c>{ string }</c>), though it takes it against <c>{ Flags }</c>. The union
    /// with an empty table takes the literal, nothing and nil in both solvers, and keeps the names in hover; it does not check them.
    /// </summary>
    private static string Optional(string type, Context context)
    {
        if (type.Contains("->", StringComparison.Ordinal))
        {
            return $"({type})?";
        }

        if (type.StartsWith("{ ", StringComparison.Ordinal) && type.EndsWith(" }", StringComparison.Ordinal)
            && context.Enums.TryGetValue(type[2..^2], out EnumInfo? flags) && flags.IsFlags)
        {
            return $"({type} | {{}})?";
        }

        return type + "?";
    }

    internal static bool IsIdentifier(string name)
    {
        if (name.Length == 0 || s_keywords.Contains(name) || !(char.IsLetter(name[0]) || name[0] == '_'))
        {
            return false;
        }

        foreach (char c in name)
        {
            if (!char.IsLetterOrDigit(c) && c != '_')
            {
                return false;
            }
        }

        return true;
    }

    /// <summary>The doc with the range an inspector gives the property appended: <c>(0 to 10)</c>.</summary>
    internal static string? WithRange(string? doc, InspectorMeta? meta)
    {
        string range = meta?.RangeText ?? "";
        return range.Length == 0 ? doc : doc is null ? $"Range: {range}." : $"{doc} (Range: {range}.)";
    }

    private static void AppendDoc(StringBuilder text, string? doc, string indent)
    {
        if (doc is not null)
        {
            Line(text, $"{indent}--- {doc}");
        }
    }
}
