using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Apogee.Reflection.Generator;

/// <summary>Writes the C# that registers the described types. Nothing in it uses reflection: lambdas that call the members directly.</summary>
internal static class Emitter
{
    private const string R = "global::Apogee.Reflection.";
    private const string V = "global::Apogee.Reflection.Value";

    public static void Emit(SourceProductionContext context, IReadOnlyList<Described> all, string assemblyName)
    {
        foreach (Described described in all)
        {
            foreach (Diagnostic diagnostic in described.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }
        }

        List<Described> valid = all.Where(d => !d.HasErrors).ToList();
        if (valid.Count == 0)
        {
            return;
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (Described described in valid.OrderBy(d => d.FullName, StringComparer.Ordinal))
        {
            string key = $"{described.Kind}:{described.RegistryName}";
            if (!seen.Add(key))
            {
                context.ReportDiagnostic(Diagnostic.Create(Diagnostics.DuplicateName, Location.None, $"Two {described.Kind.ToString().ToLowerInvariant()}s are named {described.RegistryName} in this assembly."));
                return;
            }
        }

        string registry = "ApogeeRegistry_" + new string(assemblyName.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());

        // Enums used anywhere in the assembly, once each, named E0, E1… in a stable order.
        Dictionary<string, EnumModel> enums = new(StringComparer.Ordinal);
        foreach (Described described in valid)
        {
            foreach (KeyValuePair<string, EnumModel> pair in described.Enums)
            {
                enums[pair.Key] = pair.Value;
            }
        }

        string[] enumKeys = [.. enums.Keys.OrderBy(k => k, StringComparer.Ordinal)];
        var enumNames = new Dictionary<string, string>(StringComparer.Ordinal);
        for (int i = 0; i < enumKeys.Length; i++)
        {
            enumNames[enumKeys[i]] = $"global::{registry}.Enums.E{i.ToString(CultureInfo.InvariantCulture)}";
        }

        foreach (Described described in valid.Where(d => d.Kind != DescribedKind.Component))
        {
            context.AddSource($"{described.FullName.Replace("global::", "")}.Apogee.g.cs", TypeFile(described, enumNames));
        }

        context.AddSource($"{registry}.g.cs", RegistryFile(valid, registry, enums, enumKeys));
    }

    // ---- The partial class of a class or library ---------------------------------------------------------------------------

    private static string TypeFile(Described described, Dictionary<string, string> enumNames)
    {
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated>Generated by Apogee.Reflection.Generator. Do not edit.</auto-generated>");
        text.AppendLine("#nullable enable");
        text.AppendLine("#pragma warning disable");
        if (described.Namespace.Length > 0)
        {
            text.AppendLine($"namespace {described.Namespace};");
        }

        text.AppendLine();
        int depth = 0;
        foreach (string container in described.Containers)
        {
            text.AppendLine($"{new string(' ', depth * 4)}partial {container}");
            text.AppendLine($"{new string(' ', depth * 4)}{{");
            depth++;
        }

        string indent = new(' ', depth * 4);
        text.AppendLine($"{indent}partial {described.Declaration}");
        text.AppendLine($"{indent}{{");
        var body = new StringBuilder();
        if (described.Kind == DescribedKind.Class)
        {
            body.AppendLine($"public override {R}ClassInfo Class => s_apogeeClass ??= {R}TypeRegistry.GetClass({Literal(described.RegistryName)});");
            body.AppendLine($"private static {R}ClassInfo? s_apogeeClass;");
            body.AppendLine();
            body.AppendLine($"internal static {R}ClassInfo ApogeeDescribe() =>");
            body.AppendLine($"    new({Literal(described.RegistryName)}, {Literal(described.BaseName)}, typeof({described.FullName}),");
            body.AppendLine($"        {Array("PropertyDef", described.Properties.Select(p => PropertyDef(described, p, enumNames)))},");
            body.AppendLine($"        {Array("MethodDef", described.Methods.Select(m => MethodDef(described, m, enumNames)))},");
            body.AppendLine($"        {Array("SignalDef", described.Signals.Select(s => SignalDef(described, s, enumNames)))},");
            body.AppendLine($"        factory: {(described.Creatable ? $"static () => new {described.FullName}()" : "null")}, scriptable: {Bool(described.Scriptable)}, modsBlocked: {Bool(described.ModsBlocked)}, doc: {Literal(described.Doc)});");
        }
        else
        {
            body.AppendLine($"internal static {R}LibraryInfo ApogeeDescribe() =>");
            body.AppendLine($"    new({Literal(described.RegistryName)}, {Array("MethodDef", described.Methods.Select(m => MethodDef(described, m, enumNames)))}, {Literal(described.Doc)});");
        }

        foreach (string line in body.ToString().TrimEnd().Split('\n'))
        {
            text.AppendLine(line.Length == 0 ? "" : $"{indent}    {line.TrimEnd('\r')}");
        }

        text.AppendLine($"{indent}}}");
        for (int i = depth - 1; i >= 0; i--)
        {
            text.AppendLine($"{new string(' ', i * 4)}}}");
        }

        return text.ToString();
    }

    private static string PropertyDef(Described owner, PropertyModel property, Dictionary<string, string> enums)
    {
        string getter = $"static target => {ToValue(property.Type, $"(({owner.FullName})target).{property.Name}", 0, enums)}";
        string setter = property.CanWrite
            ? $"static (object target, in {V} value) => (({owner.FullName})target).{property.Name} = {FromValue(property.Type, "value", 0)}"
            : "null";
        string meta = property.Meta is null ? "" : $", {property.Meta}";
        return $"new({Literal(property.Name)}, {Literal(property.ScriptName)}, {TypeRef(property.Type)}, {getter}, {setter}, {Literal(property.Doc)}{meta})";
    }

    private static string MethodDef(Described owner, MethodModel method, Dictionary<string, string> enums)
    {
        var parameters = Array("ParameterDef", method.Parameters.Select(p => $"new({Literal(p.Name)}, {TypeRef(p.Type)}, {Bool(p.Default is not null)})"));
        var results = Array("TypeRef", method.Results.Select(TypeRef));

        var arguments = new List<string>();
        for (int i = 0; i < method.Parameters.Count; i++)
        {
            ParameterModel parameter = method.Parameters[i];
            string index = i.ToString(CultureInfo.InvariantCulture);
            string converted = FromValue(parameter.Type, $"arguments[{index}]", 0);
            arguments.Add(parameter.Default is null ? converted : $"arguments.Length > {index} ? {converted} : {parameter.Default}");
        }

        string target = method.IsStatic ? owner.FullName : $"(({owner.FullName})target!)";
        string call = $"{target}.{method.Name}({string.Join(", ", arguments)})";

        var body = new StringBuilder();
        if (method.Results.Count == 0)
        {
            body.Append($"{call};");
        }
        else if (!method.ReturnsTuple)
        {
            body.Append($"results[0] = {ToValue(method.Results[0], call, 0, enums)};");
        }
        else
        {
            body.Append($"var result = {call};");
            for (int i = 0; i < method.Results.Count; i++)
            {
                string index = i.ToString(CultureInfo.InvariantCulture);
                body.Append($" results[{index}] = {ToValue(method.Results[i], $"result.Item{(i + 1).ToString(CultureInfo.InvariantCulture)}", 0, enums)};");
            }
        }

        string invoker = $"static (object? target, global::System.ReadOnlySpan<{V}> arguments, global::System.Span<{V}> results) => {{ {body} }}";
        return $"new({Literal(method.Name)}, {Literal(method.ScriptName)}, {Bool(method.IsStatic)}, {parameters}, {results}, {invoker}, {Literal(method.Doc)})";
    }

    private static string SignalDef(Described owner, SignalModel signal, Dictionary<string, string> enums)
    {
        var parameters = Array("ParameterDef", signal.Parameters.Select((p, i) => $"new(\"arg{(i + 1).ToString(CultureInfo.InvariantCulture)}\", {TypeRef(p)})"));
        string names = string.Join(", ", signal.Parameters.Select((_, i) => $"a{i.ToString(CultureInfo.InvariantCulture)}"));
        string values = string.Join(", ", signal.Parameters.Select((p, i) => ToValue(p, $"a{i.ToString(CultureInfo.InvariantCulture)}", 0, enums)));
        string connector = $"static (object target, {R}ScriptHandler handler) => (({owner.FullName})target).{signal.Name}.Connect(({names}) => handler([{values}]))";
        return $"new({Literal(signal.Name)}, {Literal(signal.ScriptName)}, {parameters}, {connector}, {Literal(signal.Doc)})";
    }

    // ---- The registration of the assembly -----------------------------------------------------------------------------------

    private static string RegistryFile(List<Described> valid, string registry, Dictionary<string, EnumModel> enums, string[] enumKeys)
    {
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated>Generated by Apogee.Reflection.Generator. Do not edit.</auto-generated>");
        text.AppendLine("#nullable enable");
        text.AppendLine("#pragma warning disable");
        text.AppendLine($"internal static class {registry}");
        text.AppendLine("{");
        text.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        text.AppendLine("    internal static void Register()");
        text.AppendLine("    {");
        foreach (string key in enumKeys)
        {
            EnumModel info = enums[key];
            string members = Array("EnumMemberInfo", info.Members.Select(m => $"new({Literal(m.Key)}, {m.Value.ToString(CultureInfo.InvariantCulture)}L)"));
            text.AppendLine($"        {R}TypeRegistry.RegisterIfMissing(new {R}EnumInfo({Literal(info.Name)}, {Bool(info.IsFlags)}, {members}, {Literal(info.Doc)}));");
        }

        IEnumerable<Described> ordered = valid.OrderBy(d => d.FullName, StringComparer.Ordinal);
        foreach (Described described in ordered.Where(d => d.Kind == DescribedKind.Class))
        {
            text.AppendLine($"        {R}TypeRegistry.Register({described.FullName}.ApogeeDescribe());");
        }

        foreach (Described described in ordered.Where(d => d.Kind == DescribedKind.Library))
        {
            text.AppendLine($"        {R}TypeRegistry.Register({described.FullName}.ApogeeDescribe());");
        }

        List<Described> components = ordered.Where(d => d.Kind == DescribedKind.Component).ToList();
        for (int i = 0; i < components.Count; i++)
        {
            text.AppendLine($"        {R}TypeRegistry.Register<{components[i].FullName}>(Component{i.ToString(CultureInfo.InvariantCulture)}());");
        }

        text.AppendLine("    }");

        for (int i = 0; i < components.Count; i++)
        {
            text.AppendLine();
            AppendComponent(text, components[i], i);
        }

        text.AppendLine();
        text.AppendLine("    internal static class Enums");
        text.AppendLine("    {");
        for (int i = 0; i < enumKeys.Length; i++)
        {
            string name = $"E{i.ToString(CultureInfo.InvariantCulture)}";
            text.AppendLine($"        private static {R}EnumInfo? s_{name};");
            text.AppendLine($"        internal static {R}EnumInfo {name} => s_{name} ??= {R}TypeRegistry.GetEnum({Literal(enums[enumKeys[i]].Name)});");
        }

        text.AppendLine("    }");
        text.AppendLine("}");
        return text.ToString();
    }

    private static void AppendComponent(StringBuilder text, Described component, int index)
    {
        string unsafeType = "global::System.Runtime.CompilerServices.Unsafe";
        text.AppendLine($"    private static {R}ComponentInfo Component{index.ToString(CultureInfo.InvariantCulture)}()");
        text.AppendLine("    {");
        if (component.Fields.Count == 0)
        {
            text.AppendLine($"        return new({Literal(component.RegistryName)}, typeof({component.FullName}), 0, 1, {Array("FieldDef", [])}, {Literal(component.Doc)});");
            text.AppendLine("    }");
            return;
        }

        text.AppendLine($"        var instance = default({component.FullName});");
        text.AppendLine($"        ref byte start = ref {unsafeType}.As<{component.FullName}, byte>(ref instance);");
        text.AppendLine($"        return new({Literal(component.RegistryName)}, typeof({component.FullName}), {unsafeType}.SizeOf<{component.FullName}>(),");
        text.AppendLine($"            {component.Fields.Max(f => f.Alignment).ToString(CultureInfo.InvariantCulture)}, new {R}FieldDef[]");
        text.AppendLine("            {");
        foreach (FieldModel field in component.Fields)
        {
            text.AppendLine($"                new({Literal(field.Name)}, {R}FieldKind.{field.Kind}, (int){unsafeType}.ByteOffset(ref start, ref {unsafeType}.As<{field.CsType}, byte>(ref instance.{field.Name})), {Literal(field.Doc)}{(field.Meta is null ? "" : $", {field.Meta}")}),");
        }

        text.AppendLine($"            }}, {Literal(component.Doc)});");
        text.AppendLine("    }");
    }

    // ---- Types and conversions -----------------------------------------------------------------------------------------------

    private static string TypeRef(TypeModel type)
    {
        string basic = type.Shape switch
        {
            Shape.Bool => $"{R}TypeRef.Bool",
            Shape.Int => $"{R}TypeRef.Int",
            Shape.Float => $"{R}TypeRef.Float",
            Shape.String => $"{R}TypeRef.String",
            Shape.Vector3 => $"{R}TypeRef.Vector3",
            Shape.Quaternion => $"{R}TypeRef.Quaternion",
            Shape.Entity => $"{R}TypeRef.Entity",
            Shape.Function => $"{R}TypeRef.Function",
            Shape.Table => $"{R}TypeRef.Table",
            Shape.Any => $"{R}TypeRef.Any",
            Shape.Enum => $"{R}TypeRef.Enum({Literal(type.RegistryName)}, {Bool(type.Nullable)})",
            Shape.Object => $"{R}TypeRef.Object({Literal(type.RegistryName)}, {Bool(type.Nullable)})",
            _ => $"{R}TypeRef.List({TypeRef(type.Element!)}, {Bool(type.Nullable)})",
        };
        bool markable = type.Nullable && type.Shape is not (Shape.Enum or Shape.Object or Shape.List or Shape.Any);
        return markable ? $"{basic}.AsNullable()" : basic;
    }

    private static string ToValue(TypeModel type, string expression, int depth, Dictionary<string, string> enums)
    {
        if (type.Nullable && type.IsValueType && type.Shape != Shape.Any)
        {
            string name = $"n{depth.ToString(CultureInfo.InvariantCulture)}";
            return $"({expression}) is {{ }} {name} ? {ToValueCore(type, name, depth + 1, enums)} : default({V})";
        }

        return ToValueCore(type, expression, depth, enums);
    }

    private static string ToValueCore(TypeModel type, string e, int depth, Dictionary<string, string> enums)
    {
        string x = $"x{depth.ToString(CultureInfo.InvariantCulture)}";
        return type.Shape switch
        {
            Shape.Bool => $"{V}.Bool({e})",
            Shape.Int => type.IsUnsigned64 ? $"{V}.Int(unchecked((long)({e})))" : $"{V}.Int({e})",
            Shape.Float => $"{V}.Float({e})",
            Shape.String => $"{V}.String({e})",
            Shape.Vector3 => type.IsDouble3 ? $"{V}.Vector((global::System.Numerics.Vector3)({e}))" : $"{V}.Vector({e})",
            Shape.Quaternion => $"{V}.Quat({e})",
            Shape.Enum => $"{V}.Enum({enums[type.EnumKey]}, unchecked((long)({e})))",
            Shape.Object => $"{V}.Object({e})",
            Shape.Entity => $"{V}.Entity({e})",
            Shape.Function => $"{V}.Function({e})",
            Shape.Table => $"{V}.Table({e})",
            Shape.Any => e,
            _ => $"{V}.ListOf({e}, static {x} => {ToValue(type.Element!, x, depth + 1, enums)})",
        };
    }

    private static string FromValue(TypeModel type, string v, int depth)
    {
        string core = FromValueCore(type, v, depth);
        if (!type.Nullable || type.Shape == Shape.Any)
        {
            return core;
        }

        return type.IsValueType
            ? $"{v}.IsNil ? default({type.CsType}?) : {core}"
            : $"{v}.IsNil ? null : {core}";
    }

    private static string FromValueCore(TypeModel type, string v, int depth)
    {
        string x = $"x{depth.ToString(CultureInfo.InvariantCulture)}";
        return type.Shape switch
        {
            Shape.Bool => $"{v}.ToBool()",
            Shape.Int => $"{v}.To{type.IntegerName}()",
            Shape.Float => type.IsDouble ? $"{v}.ToDouble()" : $"{v}.ToSingle()",
            Shape.String => $"{v}.ToStringValue()",
            Shape.Vector3 => type.IsDouble3 ? $"(global::Apogee.Core.Numerics.Double3){v}.ToVector3()" : $"{v}.ToVector3()",
            Shape.Quaternion => $"{v}.ToQuaternion()",
            Shape.Enum => $"({type.CsType}){v}.ToEnum()",
            Shape.Object => $"{v}.ToObject<{type.CsType}>()",
            Shape.Entity => $"{v}.ToEntity()",
            Shape.Function => $"{v}.ToFunction()",
            Shape.Table => $"{v}.ToTable()",
            Shape.Any => v,
            _ => $"{v}.ToListOf(static {x} => {FromValue(type.Element!, x, depth + 1)}){(type.ListKind == ListKind.Array ? ".ToArray()" : "")}",
        };
    }

    // ---- Text ------------------------------------------------------------------------------------------------------------------------

    private static string Array(string element, IEnumerable<string> items)
    {
        string[] list = [.. items];
        return list.Length == 0
            ? $"global::System.Array.Empty<{R}{element}>()"
            : $"new {R}{element}[] {{ {string.Join(", ", list)} }}";
    }

    private static string Bool(bool value) => value ? "true" : "false";

    private static string Literal(string? value) => value is null ? "null" : SymbolDisplay.FormatLiteral(value, quote: true);
}
