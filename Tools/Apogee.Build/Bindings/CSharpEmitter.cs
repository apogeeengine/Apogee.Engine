using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Apogee.Build.Bindings;

/// <summary>Writes an <see cref="ApiModel"/> as raw, blittable C# bindings: <c>DllImport</c>s, structs, enums and constants.</summary>
public static class CSharpEmitter
{
    private const string Header = "// <auto-generated>Generated by Tools/Apogee.Build (./build.sh bindings). Do not edit.</auto-generated>\n#nullable enable\n";

    /// <summary>Returns file name → contents for everything that goes into the project's <c>Generated/</c> folder.</summary>
    public static Dictionary<string, string> Emit(BindingConfig config, ApiModel model)
    {
        var files = new Dictionary<string, string>
        {
            [$"{config.ClassName}.Library.g.cs"] = EmitLibrary(config),
            [$"{config.ClassName}.Functions.g.cs"] = EmitFunctions(config, model),
            [$"{config.ClassName}.Constants.g.cs"] = EmitConstants(config, model),
            [$"{config.ClassName}.Types.g.cs"] = EmitTypes(config, model),
            [$"{config.ClassName}.Layout.g.cs"] = EmitLayout(config, model),
        };
        if (model.Commands.Count > 0)
        {
            files[$"{config.ClassName}.Commands.g.cs"] = EmitCommands(config, model);
        }

        if (model.Globals.Count > 0)
        {
            files[$"{config.ClassName}.Globals.g.cs"] = EmitGlobals(config, model);
        }

        return files;
    }

    /// <summary>Vulkan's commands: one class per level, each field a function pointer loaded when the instance or device exists.</summary>
    private static string EmitCommands(BindingConfig config, ApiModel model)
    {
        var text = new StringBuilder(Header);
        text.AppendLine("using Apogee.Interop;");
        text.AppendLine();
        text.AppendLine($"namespace {config.Namespace};");

        foreach ((CommandLevel level, string className, string parameters, string load) in new[]
        {
            (CommandLevel.Global, $"{config.ClassName}GlobalCommands", "", $"{config.ClassName}.LoadInstanceProc(default, "),
            (CommandLevel.Instance, $"{config.ClassName}InstanceCommands", $"{config.ClassName}Instance instance", $"{config.ClassName}.LoadInstanceProc(instance, "),
            (CommandLevel.Device, $"{config.ClassName}DeviceCommands", $"{config.ClassName}InstanceCommands instanceCommands, {config.ClassName}Device device", $"{config.ClassName}.LoadDeviceProc(instanceCommands, device, "),
        })
        {
            var commands = model.Commands.Where(c => c.Level == level).ToList();
            text.AppendLine();
            text.AppendLine($"public sealed unsafe class {className}");
            text.AppendLine("{");
            foreach (CommandModel command in commands)
            {
                text.AppendLine($"    public readonly {Pointer(command)} {command.Name};");
            }

            text.AppendLine();
            text.AppendLine($"    public {className}({parameters})");
            text.AppendLine("    {");
            foreach (CommandModel command in commands)
            {
                text.AppendLine($"        {command.Name} = ({Pointer(command)}){load}\"{command.CName}\"u8);");
            }

            text.AppendLine("    }");
            text.AppendLine("}");
        }

        return text.ToString();
    }

    /// <summary><c>using</c> lines for the binding assemblies this one's declarations refer to.</summary>
    private static void AppendForeignUsings(StringBuilder text, ApiModel model)
    {
        foreach (string ns in model.Usings)
        {
            text.AppendLine($"using {ns};");
        }
    }

    private static string Pointer(CommandModel command) =>
        $"delegate* unmanaged[Cdecl]<{string.Join(", ", command.Parameters.Select(p => p.Type).Append(command.ReturnType))}>";

    private static string EmitLibrary(BindingConfig config)
    {
        var text = new StringBuilder(Header);
        text.AppendLine("using System.Reflection;");
        text.AppendLine("using System.Runtime.CompilerServices;");
        text.AppendLine("using Apogee.Interop;");
        text.AppendLine();
        text.AppendLine("[assembly: DisableRuntimeMarshalling]");
        text.AppendLine();
        text.AppendLine($"namespace {config.Namespace};");
        text.AppendLine();
        text.AppendLine($"internal static class {config.ClassName}Library");
        text.AppendLine("{");
        text.AppendLine("    [ModuleInitializer]");
        text.AppendLine("    internal static void Register() =>");
        text.AppendLine($"        NativeLibraries.Register(typeof({config.ClassName}).Assembly, \"{config.Library.Name}\",");
        text.AppendLine($"            {Array(config.Library.Linux)}, {Array(config.Library.Windows)}, {Array(config.Library.Macos)});");
        text.AppendLine("}");
        return text.ToString();
    }

    private static string Array(string[] names) => "[" + string.Join(", ", names.Select(n => $"\"{n}\"")) + "]";

    private static string EmitFunctions(BindingConfig config, ApiModel model)
    {
        var text = new StringBuilder(Header);
        text.AppendLine("using System.Runtime.InteropServices;");
        text.AppendLine("using Apogee.Interop;");
        AppendForeignUsings(text, model);
        text.AppendLine();
        text.AppendLine($"namespace {config.Namespace};");
        text.AppendLine();
        text.AppendLine($"public static unsafe partial class {config.ClassName}");
        text.AppendLine("{");
        text.AppendLine($"    internal const string LibraryName = \"{config.Library.Name}\";");
        foreach (FunctionModel function in model.Functions)
        {
            text.AppendLine();
            AppendDoc(text, function.Doc, "    ");
            text.AppendLine($"    [DllImport(LibraryName, EntryPoint = \"{function.CName}\", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]");
            string parameters = string.Join(", ", function.Parameters.Select(p => $"{p.Type} {Naming.Parameter(p.Name)}"));
            text.AppendLine($"    public static extern {function.ReturnType} {function.Name}({parameters});");
        }

        text.AppendLine("}");
        return text.ToString();
    }

    /// <summary>
    /// Exported variables as <c>ref</c> properties over the symbol's address, found by name on first use. A variable is read
    /// through the property (<c>Ecs.OnUpdate</c>), so it is always the library's value, never a copy taken at startup.
    /// </summary>
    private static string EmitGlobals(BindingConfig config, ApiModel model)
    {
        var text = new StringBuilder(Header);
        text.AppendLine("using System;");
        text.AppendLine("using System.Runtime.InteropServices;");
        text.AppendLine("using Apogee.Interop;");
        AppendForeignUsings(text, model);
        text.AppendLine();
        text.AppendLine($"namespace {config.Namespace};");
        text.AppendLine();
        text.AppendLine($"public static unsafe partial class {config.ClassName}");
        text.AppendLine("{");
        text.AppendLine("    private static nint GlobalAddress(string symbol)");
        text.AppendLine("    {");
        text.AppendLine($"        if (!NativeLibraries.TryLoad(typeof({config.ClassName}).Assembly, LibraryName, out nint library))");
        text.AppendLine("        {");
        text.AppendLine("            throw new DllNotFoundException(LibraryName);");
        text.AppendLine("        }");
        text.AppendLine();
        text.AppendLine("        return NativeLibrary.GetExport(library, symbol);");
        text.AppendLine("    }");
        foreach (GlobalModel global in model.Globals)
        {
            string field = "s_address" + global.Name;
            string reference = global.IsConst ? "ref readonly" : "ref";
            text.AppendLine();
            text.AppendLine($"    private static nint {field};");
            AppendDoc(text, global.Doc, "    ");
            text.AppendLine($"    public static {reference} {global.Type} {global.Name} =>");
            text.AppendLine($"        ref *({global.Type}*)({field} != 0 ? {field} : ({field} = GlobalAddress(\"{global.CName}\")));");
        }

        text.AppendLine("}");
        return text.ToString();
    }

    private static string EmitConstants(BindingConfig config, ApiModel model)
    {
        var text = new StringBuilder(Header);
        text.AppendLine($"namespace {config.Namespace};");
        text.AppendLine();
        text.AppendLine($"public static partial class {config.ClassName}");
        text.AppendLine("{");
        foreach (ConstantModel constant in model.Constants)
        {
            string value = constant.Type == "string" ? $"\"{constant.Value}\"" : constant.Value;
            text.AppendLine($"    public const {constant.Type} {constant.Name} = {value};");
        }

        text.AppendLine("}");
        return text.ToString();
    }

    private static string EmitTypes(BindingConfig config, ApiModel model)
    {
        var text = new StringBuilder(Header);
        text.AppendLine("using System;");
        text.AppendLine("using System.Runtime.CompilerServices;");
        text.AppendLine("using System.Runtime.InteropServices;");
        text.AppendLine("using Apogee.Interop;");
        AppendForeignUsings(text, model);
        text.AppendLine();
        text.AppendLine($"namespace {config.Namespace};");

        foreach (HandleModel handle in model.Handles)
        {
            string value = handle.Dispatchable ? "nint" : "ulong";
            text.AppendLine();
            text.AppendLine($"public readonly struct {handle.Name}({value} value)");
            text.AppendLine("{");
            text.AppendLine($"    public readonly {value} Value = value;");
            text.AppendLine();
            text.AppendLine("    public bool IsNull => Value == 0;");
            text.AppendLine("}");
        }

        foreach (EnumModel enumeration in model.Enums)
        {
            text.AppendLine();
            AppendDoc(text, enumeration.Doc, "");
            if (enumeration.IsFlags)
            {
                text.AppendLine("[Flags]");
            }

            text.AppendLine($"public enum {enumeration.Name} : {enumeration.Underlying}");
            text.AppendLine("{");
            foreach (EnumMemberModel member in enumeration.Members)
            {
                text.AppendLine($"    {member.Name} = {member.Value},");
            }

            text.AppendLine("}");
        }

        foreach (StructModel structure in model.Structs)
        {
            text.AppendLine();
            AppendDoc(text, structure.Doc, "");
            text.AppendLine(structure.HasOverlap ? "[StructLayout(LayoutKind.Explicit)]"
                : structure.PackDependent ? "[StructLayout(LayoutKind.Sequential, Pack = SteamPack.Callback)]"
                : structure.FixedPack > 0 ? $"[StructLayout(LayoutKind.Sequential, Pack = {structure.FixedPack})]" : "[StructLayout(LayoutKind.Sequential)]");
            text.AppendLine($"public unsafe partial struct {structure.Name}");
            text.AppendLine("{");
            foreach (FieldModel field in structure.Fields)
            {
                if (structure.HasOverlap)
                {
                    text.AppendLine($"    [FieldOffset({field.Offset.ToString(CultureInfo.InvariantCulture)})]");
                }

                text.AppendLine(field.FixedLength > 0
                    ? $"    public fixed {field.Type} {field.Name}[{field.FixedLength}];"
                    : $"    public {field.Type} {field.Name};");
            }

            if (structure.StructureType is not null)
            {
                text.AppendLine();
                text.AppendLine("    /// <summary>Sets <see cref=\"SType\"/>. <c>default</c> and arrays of this struct do not run it.</summary>");
                text.AppendLine($"    public {structure.Name}()");
                text.AppendLine("    {");
                text.AppendLine($"        SType = VkStructureType.{structure.StructureType};");
                text.AppendLine("    }");
            }

            text.AppendLine("}");
        }

        foreach (InlineArrayModel array in model.InlineArrays.Values)
        {
            text.AppendLine();
            text.AppendLine($"[InlineArray({array.Length})]");
            text.AppendLine($"public unsafe struct {array.Name}");
            text.AppendLine("{");
            text.AppendLine($"    private {array.ElementType} _element0;");
            text.AppendLine("}");
        }

        return text.ToString();
    }

    /// <summary>The sizes clang computed, so a test can check that the C# layouts match the C ones.</summary>
    private static string EmitLayout(BindingConfig config, ApiModel model)
    {
        var text = new StringBuilder(Header);
        text.AppendLine("using System;");
        text.AppendLine();
        text.AppendLine($"namespace {config.Namespace};");
        text.AppendLine();
        text.AppendLine($"public static class {config.ClassName}Layout");
        text.AppendLine("{");
        if (model.Globals.Count > 0)
        {
            text.AppendLine("    /// <summary>The symbols of the exported variables, so a test can check that the library has them.</summary>");
            text.AppendLine("    public static readonly string[] ExportedGlobals =");
            text.AppendLine("    [");
            foreach (GlobalModel global in model.Globals)
            {
                text.AppendLine($"        \"{global.CName}\",");
            }

            text.AppendLine("    ];");
            text.AppendLine();
        }

        HashSet<string> longDependent = StructsDependingOnLong(model);
        var sized = model.Structs.Where(s => s.Size > 0 && s.Fields.Count > 0).ToList();
        AppendSizes(text, "Sizes", "Struct types and their size in bytes in C on a 64-bit target.", sized.Where(s => !longDependent.Contains(s.Name) && !s.PackDependent));

        // C's long is 8 bytes on Linux and macOS and 4 on Windows, where these structs have another (correct) size.
        var dependent = sized.Where(s => longDependent.Contains(s.Name)).ToList();
        if (dependent.Count > 0)
        {
            text.AppendLine();
            AppendSizes(text, "LongDependentSizes", "Structs that contain a C long, with their size where long is 8 bytes (not Windows).", dependent);
        }

        // Steam's callback structs are packed to 4 bytes on Linux and macOS and to 8 on Windows (steamclientpublic.h): a size for each.
        var packed = sized.Where(s => s.PackDependent).ToList();
        if (packed.Count > 0)
        {
            text.AppendLine();
            text.AppendLine("    /// <summary>Structs whose layout depends on Steam's callback packing: the size with 4-byte packing (Linux and macOS) and with 8-byte packing (Windows).</summary>");
            text.AppendLine("    public static readonly (global::System.Type Type, int Pack4, int Pack8)[] CallbackPackSizes =");
            text.AppendLine("    [");
            foreach (StructModel structure in packed)
            {
                text.AppendLine($"        (typeof({structure.Name}), {structure.Size.ToString(CultureInfo.InvariantCulture)}, {structure.LargePackSize.ToString(CultureInfo.InvariantCulture)}),");
            }

            text.AppendLine("    ];");
        }

        text.AppendLine("}");
        return text.ToString();
    }

    private static void AppendSizes(StringBuilder text, string name, string summary, IEnumerable<StructModel> structs)
    {
        text.AppendLine($"    /// <summary>{summary}</summary>");
        text.AppendLine($"    public static readonly (global::System.Type Type, int Size)[] {name} =");
        text.AppendLine("    [");
        foreach (StructModel structure in structs)
        {
            text.AppendLine($"        (typeof({structure.Name}), {structure.Size.ToString(CultureInfo.InvariantCulture)}),");
        }

        text.AppendLine("    ];");
    }

    /// <summary>The structs whose size depends on the size of C's long: they contain a <c>CLong</c> or <c>CULong</c> by value, directly or through another struct or inline array.</summary>
    private static HashSet<string> StructsDependingOnLong(ApiModel model)
    {
        var types = new HashSet<string> { "CLong", "CULong" };
        foreach (InlineArrayModel array in model.InlineArrays.Values.Where(a => types.Contains(a.ElementType)))
        {
            types.Add(array.Name);
        }

        int count;
        do
        {
            count = types.Count;
            foreach (StructModel structure in model.Structs.Where(s => s.Fields.Any(f => types.Contains(f.Type))))
            {
                types.Add(structure.Name);
            }

            foreach (InlineArrayModel array in model.InlineArrays.Values.Where(a => types.Contains(a.ElementType)))
            {
                types.Add(array.Name);
            }
        }
        while (types.Count != count);

        return model.Structs.Select(s => s.Name).Where(types.Contains).ToHashSet();
    }

    private static void AppendDoc(StringBuilder text, string? doc, string indent)
    {
        if (doc is not null)
        {
            text.AppendLine($"{indent}/// <summary>{doc}</summary>");
        }
    }
}
