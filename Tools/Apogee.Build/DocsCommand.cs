using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;

namespace Apogee.Build;

/// <summary>
/// <c>./build.sh docs [serve]</c>: builds the API reference pages, then the site. The C# API comes from DocFX (<c>Tools/docfx/docfx.json</c>, one Markdown page per type),
/// the Luau API from the runtime (<c>--luau-docs</c>); both go into <c>Docs/api</c>, where git ignores them, and MkDocs builds the whole of <c>Docs</c> into <c>Bin/site</c>.
/// </summary>
public static class DocsCommand
{
    public static int Run(string root, string[] args)
    {
        bool serve = args.Length == 1 && args[0] == "serve";
        if (args.Length > 0 && !serve)
        {
            Console.Error.WriteLine("Usage: ./build.sh docs [serve]");
            return 1;
        }

        try
        {
            int status = CSharpApi(root);
            if (status == 0)
            {
                status = Start(root, "dotnet", "run", "--project", "Source/Apogee.Runtime", "-c", "Release", "--", "--luau-docs", Path.Combine("Docs", "api", "luau"));
            }

            if (status == 0)
            {
                status = serve ? Start(root, "mkdocs", "serve") : Start(root, "mkdocs", "build", "--strict");
            }

            return status;
        }
        catch (Exception e) when (e is IOException or System.ComponentModel.Win32Exception)
        {
            Console.Error.WriteLine($"docs: {e.Message}");
            return 1;
        }
    }

    private static int CSharpApi(string root)
    {
        // DocFX reads the projects through MSBuild: the source generator that writes the reflection registry has to be built first, or every [ApogeeClass] misses its generated members.
        int status = Start(root, "dotnet", "build", Path.Combine("Source", "Apogee.Runtime"), "-c", "Release", "--nologo", "-v", "q");
        if (status == 0)
        {
            status = Start(root, "dotnet", "tool", "restore");
        }
        if (status == 0)
        {
            status = Start(root, "dotnet", "docfx", "metadata", Path.Combine("Tools", "docfx", "docfx.json"));
        }

        if (status != 0)
        {
            return status;
        }

        string generated = Path.Combine(root, "Bin", "docfx", "csharp");
        string target = Path.Combine(root, "Docs", "api", "csharp");
        foreach (string stale in Directory.EnumerateFiles(target).Where(f => Path.GetFileName(f) != "index.md"))
        {
            File.Delete(stale);
        }

        foreach (string page in Directory.EnumerateFiles(generated, "*.md"))
        {
            File.Copy(page, Path.Combine(target, Path.GetFileName(page)), overwrite: true);
        }

        // The namespaces are the top level entries of DocFX's table of contents: "- name: Apogee.Core".
        List<string> namespaces = [.. File.ReadLines(Path.Combine(generated, "toc.yml"))
            .Where(line => line.StartsWith("- name: ", StringComparison.Ordinal))
            .Select(line => line["- name: ".Length..].Trim())];
        File.WriteAllText(
            Path.Combine(target, "namespaces.md"),
            "# Namespaces\n\nGenerated by DocFX from the XML documentation in `Source/`: do not edit.\n\n" + string.Concat(namespaces.Select(n => $"- [{n}]({n}.md)\n")));
        Console.WriteLine($"C# API: {namespaces.Count} namespaces");
        return 0;
    }

    private static int Start(string root, string program, params string[] arguments)
    {
        var info = new ProcessStartInfo(program) { WorkingDirectory = root };
        foreach (string argument in arguments)
        {
            info.ArgumentList.Add(argument);
        }

        using Process process = Process.Start(info) ?? throw new IOException($"Could not start {program}");
        process.WaitForExit();
        return process.ExitCode;
    }
}
